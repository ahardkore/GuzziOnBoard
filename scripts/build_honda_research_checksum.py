#!/usr/bin/env python3
"""Export source-scoped Honda checksum candidates for the offline browser tool."""
from __future__ import annotations
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from guzzionboard.protocol.honda_cbr600rr import (  # noqa: E402
    HONDA_EXAMPLE_INFERRED_IDS, HONDA_RESEARCH_CHECKSUM_OFFSETS,
    HONDA_RESEARCH_COMMENTED_IDS, HONDA_RESEARCH_IMAGE_SIZES,
    HONDA_RESEARCH_LAYOUTS, HONDA_RESEARCH_STARTS, HONDA_TABLE_ONLY_IDS,
    HONDA_FAMILY_INFERRED_IDS, HONDA_SOURCE_CONFLICTS, HONDA_VFR_RESEARCH_IDS,
    HONDA_RESEARCH_EXAMPLE_PARTS,
)


def generate():
    candidates = {}
    for ecm_id, offset in HONDA_RESEARCH_CHECKSUM_OFFSETS.items():
        part, id_offset = HONDA_RESEARCH_LAYOUTS[ecm_id]
        size = HONDA_RESEARCH_IMAGE_SIZES[ecm_id]
        if not (0 < offset < size and 0 <= id_offset <= size - len(ecm_id)):
            raise ValueError(f'out-of-range candidate: {part}')
        candidates[ecm_id.hex().upper()] = {
            'part': part, 'size': size, 'id_offset': id_offset, 'checksum_offset': offset,
            'read_start': HONDA_RESEARCH_STARTS[ecm_id],
            'id_basis': 'table-only' if ecm_id in HONDA_TABLE_ONLY_IDS else
                        'family-inferred; named example conflicts' if ecm_id in HONDA_FAMILY_INFERRED_IDS else
                        'example-inferred' if ecm_id in HONDA_EXAMPLE_INFERRED_IDS else 'table-and-example',
            'conflict': (f"Source table part {part} differs from example filename {HONDA_RESEARCH_EXAMPLE_PARTS[ecm_id]}."
                         if ecm_id in HONDA_RESEARCH_EXAMPLE_PARTS else HONDA_SOURCE_CONFLICTS.get(ecm_id, '')),
            'source': 'AlexKovalevich/HondaECU db0a6cb8' if ecm_id in HONDA_VFR_RESEARCH_IDS or ecm_id in HONDA_RESEARCH_COMMENTED_IDS else
                      'aeaphichart/HondaECU-1 b59ae98b; Alex checksum table for K26' if part.startswith('38770-K26-') else
                      'aeaphichart/HondaECU-1 b59ae98b',
            'commented': ecm_id in HONDA_RESEARCH_COMMENTED_IDS,
        }
    return ('/* Generated by scripts/build_honda_research_checksum.py; do not edit. */\n'
            "'use strict';\n"
            'const HONDA_CHECKSUM_CANDIDATES = ' + json.dumps(candidates, indent=2, sort_keys=True) + ';\n'
            "if (typeof module !== 'undefined' && module.exports) module.exports = HONDA_CHECKSUM_CANDIDATES;\n")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    dest = ROOT / 'web' / 'honda-checksum-candidates.js'
    content = generate()
    if args.check:
        if not dest.exists() or dest.read_text() != content:
            raise SystemExit('Honda checksum candidate list is stale')
        print('Honda checksum candidate list is up to date')
    else:
        dest.write_text(content)
        print(f'Wrote {dest.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
